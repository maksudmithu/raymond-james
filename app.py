def fetch_token(token, state_code):
  advisors, page, total = [], 1, 1
  with requests.Session(impersonate="chrome120") as s:
    while page <= total:
      try:
        res = s.get(
            API_URL,
            params={"sort": "relevant", "name": token, "page": str(page)},
            headers=HEADERS,
            timeout=10,
        )
        if res.status_code != 200:
          break
        data = res.json()
        total, results = data.get("totalPages", 1), data.get("results", [])
        if not results:
          break

        for item in results:
          branch, addr = item.get("branch") or {}, (
              item.get("branch") or {}
          ).get("address") or {}
          if addr.get("state", "").strip().upper() == state_code.upper():
            adv_id = item.get("advisorID")
            if adv_id:
              des = (
                  ", ".join(item.get("designations") or [])
                  .replace("<SUP>", "")
                  .replace("</SUP>", "")
                  .replace("&reg;", "®")
              )
              advisors.append({
                  "Advisor ID": adv_id,
                  "Name": item.get("name") or "",
                  "Title": item.get("title") or "",
                  "Designations": des,
                  "Team Name": item.get("teamName") or "",
                  "Email": item.get("emailAddress") or "",
                  "Phone": item.get("phone") or "",
                  "Website": item.get("websiteUrl") or "",
                  "Profile URL": (
                      f"https://www.raymondjames.com{item.get('advisorProfileUrl')}"
                      if item.get("advisorProfileUrl")
                      else ""
                  ),
                  "Branch Name": branch.get("header") or "",
                  "Branch ID": branch.get("branchID") or "",
                  "Street": addr.get("line1") or "",
                  "City": addr.get("city") or "",
                  "State": state_code.upper(),
                  "Zip": addr.get("zip") or "",
                  "Subsidiary": item.get("subsidiary") or "",
              })
        page += 1
      except:
        break
  return token, advisors


